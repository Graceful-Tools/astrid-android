#!/usr/bin/env python3
"""Port translations from astrid-ios into res/values-<lang>/ (AATD-23).

Each English string in app/src/main/res/values/{strings,core_keys}.xml is matched to an iOS key —
by name first (auth_tagline <-> "auth.tagline", core_repeating_weekly <-> "repeating.weekly"),
then by identical English text in en.lproj — and that key's translation is written for every
language iOS ships. Unmatched strings fall back to English at runtime, which Android does by itself.
Re-runnable; the generated files carry a header saying so. Usage: scripts/port-ios-strings.py [--ios ../astrid-ios]
"""
import html, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ios = sys.argv[sys.argv.index('--ios') + 1] if '--ios' in sys.argv else os.path.join(root, '..', 'astrid-ios')
loc = os.path.join(ios, 'Astrid App', 'Resources', 'Localizations')
res = os.path.join(root, 'app', 'src', 'main', 'res')
# iOS folder -> Android resource qualifier
LANGS = {'de': 'de', 'es': 'es', 'fr': 'fr', 'it': 'it', 'ja': 'ja', 'ko': 'ko', 'nl': 'nl',
         'pt': 'pt', 'ru': 'ru', 'zh-Hans': 'b+zh+Hans', 'zh-Hant': 'b+zh+Hant'}

def read_strings(path):
    out = {}
    text = open(path, encoding='utf-8').read()
    for key, value in re.findall(r'^\s*"((?:[^"\\]|\\.)+)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', text, re.M):
        out[key] = value.encode().decode('unicode_escape').encode('latin-1').decode('utf-8')
    return out

def android_strings(path):
    text = open(path, encoding='utf-8').read()
    return re.findall(r'<string name="([a-z0-9_]+)"([^>]*)>(.*?)</string>', text, re.S)

def unescape(v):
    return html.unescape(v).replace("\\'", "'").replace('\\"', '"')

def ios_to_android(v):
    # %@ / %d -> positional %1$s / %1$d, in order
    n = [0]
    def pos(m):
        n[0] += 1
        return '%%%d$%s' % (n[0], 's' if m.group(1) == '@' else m.group(1))
    v = re.sub(r'%(@|d|ld|lld|s)', lambda m: pos(type('m', (), {'group': lambda self, i: {'ld': 'd', 'lld': 'd'}.get(m.group(1), m.group(1))})()), v)
    v = html.escape(v, quote=False).replace("'", "\\'").replace('"', '\\"')
    return v

en = read_strings(os.path.join(loc, 'en.lproj', 'Localizable.strings'))
by_text = {}
for k, v in en.items():
    by_text.setdefault(v.strip(), k)

entries = []
for fname in ('strings.xml', 'core_keys.xml'):
    for name, attrs, value in android_strings(os.path.join(res, 'values', fname)):
        if name == 'app_name' or 'translatable="false"' in attrs:
            continue
        base = name[5:] if name.startswith('core_') else name
        candidates = [base.replace('_', '.', 1), base.replace('_', '.')]
        key = next((c for c in candidates if c in en), None) or by_text.get(unescape(value).strip())
        entries.append((name, attrs, value, key))

matched = sum(1 for e in entries if e[3])
for ios_lang, qualifier in LANGS.items():
    path = os.path.join(loc, f'{ios_lang}.lproj', 'Localizable.strings')
    if not os.path.exists(path):
        continue
    tr = read_strings(path)
    # The core's label keys are translated in astrid-windows (German so far): take those too.
    windows = {}
    resw = os.path.join(root, '..', 'astrid-windows', 'app', 'Astrid.App', 'Strings', f'{ios_lang}-DE' if ios_lang == 'de' else ios_lang, 'Resources.resw')
    if os.path.exists(resw):
        for wname, wvalue in re.findall(r'<data name="([a-z0-9_]+)"[^>]*>\s*<value>([^<]*)</value>', open(resw, encoding='utf-8').read()):
            windows['core_' + wname] = re.sub(r'\{(\d)\}', lambda m: '%%%d$s' % (int(m.group(1)) + 1), html.unescape(wvalue))
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f'<!-- GENERATED by scripts/port-ios-strings.py from astrid-ios {ios_lang}.lproj. Re-run; do not hand-edit. -->',
             '<resources>']
    count = 0
    for name, attrs, value, key in entries:
        fmt = ' formatted="false"' if 'formatted="false"' in attrs else ''
        if name in windows and windows[name].strip():
            text = html.escape(windows[name], quote=False).replace("'", "\\'")
            lines.append(f'    <string name="{name}"{fmt}>{text}</string>')
            count += 1
        elif key and key in tr and tr[key].strip():
            lines.append(f'    <string name="{name}"{fmt}>{ios_to_android(tr[key])}</string>')
            count += 1
    lines.append('</resources>')
    out_dir = os.path.join(res, f'values-{qualifier}')
    os.makedirs(out_dir, exist_ok=True)
    open(os.path.join(out_dir, 'strings.xml'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{ios_lang:8} {count}/{len(entries)}')
print(f'matched to an iOS key: {matched}/{len(entries)}')
print('unmatched:', ', '.join(n for n, _, _, k in entries if not k))
